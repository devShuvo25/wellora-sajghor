export function getRoleDashboardConfig(role?: string | null): RoleDashboardConfig {
  const normalized = (role || 'admin').toLowerCase().trim();
  if (normalized === 'admin' || normalized === 'administrator') {
    return DASHBOARD_CONFIGS.admin;
  }
  if (normalized === 'distributor' || normalized === 'partner') {
    return DASHBOARD_CONFIGS.distributor;
  }
  if (normalized === 'customer' || normalized === 'user') {
    return DASHBOARD_CONFIGS.customer;
  }
  return DASHBOARD_CONFIGS.admin;
}
